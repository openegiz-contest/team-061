class Walker:
    """Состояние движения по маршруту одного человека."""

    def __init__(self, site, wps, seed):
        wps=[(*NAV.safe(site,(q[0],q[1])),q[2],q[3]) for q in wps]
        self.site, self.wps = site, wps
        self.i = seed % len(wps)
        self.u, self.r = wps[self.i][0], wps[self.i][1]
        self.dwell = wps[self.i][3] * ((seed * 37) % 100) / 100.0
        self.speed = 1.2 + 0.1 * (seed % 3)
        self.heading = 0.0
        self.act = wps[self.i][2]
        self.moving = False

    def step(self, dt=1.0):
        u0, r0, act, dwell = self.wps[self.i]
        if self.dwell > 0:
            self.dwell -= dt
            self.moving = False
            self.act = act
            return
        j = (self.i + 1) % len(self.wps)
        target=self.wps[j][:2]
        if getattr(self,'nav_target',None)!=(j,target):
            self.nav_path=NAV.route(self.site,(self.u,self.r),target);self.nav_k=1;self.nav_target=(j,target)
        if self.nav_k>=len(self.nav_path):
            if len(self.nav_path)>1:self.i,self.dwell=j,self.wps[j][3];self.nav_target=None
            self.moving=False;self.act='ожидание безопасного прохода';return
        u1,r1=self.nav_path[self.nav_k]
        d = math.hypot(u1 - self.u, r1 - self.r)
        if d < 0.6:
            self.nav_k+=1
            if self.nav_k>=len(self.nav_path):self.i,self.dwell=j,self.wps[j][3];self.nav_target=None
            self.moving = False
            self.act = self.wps[j][2]
            return
        k = min(1.0, self.speed * dt / d)
        self.heading = math.atan2(-(r1 - self.r), u1 - self.u)
        self.u += (u1 - self.u) * k
        self.r += (r1 - self.r) * k
        self.moving = True
        self.act = "в пути: " + self.wps[j][2] if self.wps[j][2] != "переход" else "в пути"


