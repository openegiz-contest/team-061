def ws_plan(ridx, occ):
    """Маршрут сотрудника мастерской по занятым постам: occ — [(номер поста 0..2, причина ремонта)]. Без самосвалов — подготовка и склад."""
    if not occ:
        return [[(-42, -2, "в конторе: наряды", 400), (-36, 10, "обход мастерской", 60)],
                [(-38, -9, "инструментальная: подготовка", 300), (-30, 10, "получение инструмента", 90)],
                [(-26, 16, "мойка узлов", 250), (30, 12, "склад: подбор", 120)],
                [(42, -2, "склад запчастей: учёт", 500), (46, 6, "приёмка поставки", 200)],
                [(-30, -13, "кабина крана: ожидание", 600), (-30, -13, "осмотр крана", 120)]][ridx]
    out = []
    for k, why in occ:
        bu = BAY_U[k]
        t = why or "ремонт"
        if ridx == 0:
            out += [(bu + 7, 6, f"пост {k + 1}: приёмка ремонта ({t})", 120), (bu - 7, 6, f"пост {k + 1}: контроль качества", 90)]
        elif ridx == 1:
            out += [(bu - 4, -1, f"пост {k + 1}: ремонт — {t}", 520), (bu - 4, -6, f"пост {k + 1}: снятие и установка узла", 420)]
        elif ridx == 2:
            out += [(bu + 4, 1, f"пост {k + 1}: ремонт — {t}", 480), (bu + 5, -5, f"пост {k + 1}: проверка после ремонта", 300)]
        elif ridx == 3:
            out += [(42, -2, "склад запчастей: выдача", 150), (bu + 8, 8, f"подача запчасти на пост {k + 1}", 100)]
        else:
            out += [(bu, -9, f"мостовой кран: подъём узла, пост {k + 1}", 260), (bu, 9, f"мостовой кран: перенос, пост {k + 1}", 120)]
    if ridx == 0:
        out.append((-42, -2, "в конторе: оформление наряда", 200))
    return out
